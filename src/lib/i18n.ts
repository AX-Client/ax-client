const LANGS: Record<Lang, Dict> = { en, de, fr, es, zh };

export const LANG_LIST: Array<{ code: Lang; label: string }> = [
  { code: "en", label: "English" },
  { code: "de", label: "Deutsch" },
  { code: "fr", label: "Français" },
  { code: "es", label: "Español" },
  { code: "zh", label: "中文" },
];

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const base = LANGS[lang][key] ?? en[key] ?? key;
  if (!vars) return base;
  return base.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const lang = useApp((s) => (s.languageDraft ?? s.settings?.language ?? "en") as Lang);
  return useCallback((key, vars) => translate(lang, key, vars), [lang]);
}